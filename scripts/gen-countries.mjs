/**
 * Regenerates src/lib/countries.ts.
 *
 * The codes come from country-flag-icons, which ships one SVG per ISO 3166-1
 * alpha-2 entry, and the names from Intl.DisplayNames so they are spelled the
 * way a browser would spell them. Anything Intl does not recognise as a region
 * is dropped — that clears out entries like EU which are not countries.
 *
 *   node scripts/gen-countries.mjs
 */
import { readdirSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const FLAG_DIR = join(process.cwd(), "node_modules", "country-flag-icons", "3x2")
const OUT = join(process.cwd(), "src", "lib", "countries.ts")

const displayNames = new Intl.DisplayNames(["en"], { type: "region" })

const countries = readdirSync(FLAG_DIR)
  .filter((file) => file.endsWith(".svg"))
  .map((file) => file.replace(".svg", ""))
  .filter((code) => /^[A-Z]{2}$/.test(code))
  .map((code) => {
    let name
    try {
      name = displayNames.of(code)
    } catch {
      return null
    }
    // Intl hands back the code itself when it does not know the region.
    return !name || name === code ? null : { code, name }
  })
  .filter(Boolean)
  .sort((a, b) => a.name.localeCompare(b.name, "en"))

const body = countries
  .map(({ code, name }) => `  { code: ${JSON.stringify(code)}, name: ${JSON.stringify(name)} }`)
  .join(",\n")

writeFileSync(
  OUT,
  `// Generated by scripts/gen-countries.mjs — do not edit by hand.

/** An ISO 3166-1 country, for the delivery address. */
export interface Country {
  /** ISO 3166-1 alpha-2. */
  code: string
  name: string
}

/** Every country, alphabetically by name. */
export const COUNTRIES: Country[] = [
${body}
]

/** Where the shop is, and what a new address starts as. */
export const DEFAULT_COUNTRY_CODE = "NG"

const BY_CODE = new Map(COUNTRIES.map((country) => [country.code, country]))

/** The country's name, or the code back when it is not one we know. */
export function getCountryName(code: string) {
  return BY_CODE.get(code)?.name ?? code
}

export function isCountryCode(value: unknown): value is string {
  return typeof value === "string" && BY_CODE.has(value)
}
`,
  "utf8"
)

console.log(`wrote ${countries.length} countries to ${OUT}`)
